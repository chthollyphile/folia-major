// 把 zh-CN 文案转成繁体中文时的后置补词表。
//
// 键是 **OpenCC cn→twp 转换之后的形状**，不是简体原文。这样每条规则都能被程序检查
// 「它真的在 twp 输出里出现过」，不会留一条永远不命中的死规则
// （test/unit/i18n/traditionalLocale.test.ts 在断言这一点）。
//
// 为什么需要这张表：twp 覆盖了绝大部分通用 IT 词汇——软件→軟體、设置→設定、
// 文件夹→資料夾、内存→記憶體、缓存→快取、视频→影片、优化→最佳化、端口→埠、
// 参数→引數、界面→介面、算法→演算法——但仍有少数词它没有条目，直转会留下
// 简体的表达习惯，读起来像「简体字写成的台湾文案」。
//
// 收录标准是**台湾真的不这么说**，不是「我觉得更好听」。说不清的不要加：
// 每加一条都是在替维护者做语言决策。已知遗留（本地→本機、崩潰→當機、反饋→回饋等）
// 一律不在这里动，理由写在 PR 说明里。

