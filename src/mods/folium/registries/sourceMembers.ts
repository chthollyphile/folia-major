// src/mods/folium/registries/sourceMembers.ts
// Where every member of the host's internal provider contract (src/types/onlineMusic.ts, 165 of them: the
// member matrix dev/folium/folium-2-member-matrix.md) comes from for a Folium 2.0 source, as the adapter
// (sources.ts) builds it. Data only, read by test/unit/mod-system/foliumSourceMembers.test.ts, which fails when
// the internal contract gains a member this table does not place, and when a place it names is not in the
// public contract. The types below fail the type check the same way.
//
// A destination is one of:
//   - `<capability>@<version>.<member>`: that member of that capability (sources/contract.ts);
//   - `field <name>`: a field of the registration (FoliumSourceDef);
//   - `derived <how>`: the host works it out (capability flags, internal objects that group a capability's members);
//   - `handle.notify`: the source tells the host through its handle;
//   - `dto`: read from the song DTO itself (plan §4.3);
//   - `adapter`: the adapter's own, from what the source gives;
//   - `none <why>`: not in the public contract, and the adapter gives none.
// The matrix §4 choices this follows (shortName, getAvailability, the songs@1 members, getSongMetadata as the DTO,
// and the four left out) are working assumptions until the maintainer confirms them.

